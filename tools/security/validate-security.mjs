function toPosix(p) {
  return p.replace(/\\/g, '/');
}

function isPlaceholderEnvValue(value) {
  const normalized = value.trim().replace(/^['"]|['"]$/g, '');
  if (!normalized) return true;
  if (/^(placeholder|example|your_|sua_|seu_|change-me|changeme|xxx|fake|mock|demo|test|\[)/i.test(normalized)) {
    return true;
  }
  if (normalized.includes('process.env.')) return true;
  return false;
}

function shouldExclude(filePath, excludePatterns) {
  return excludePatterns.some((pattern) => {
    if (pattern.endsWith('/')) return filePath.includes(pattern);
    return filePath.endsWith(pattern) || filePath.includes(pattern);
  });
}

function shouldScan(filePath) {
  const normalized = toPosix(filePath);
  const hasPrefix = SCAN_PREFIXES.some((prefix) => normalized.startsWith(prefix));
  if (!hasPrefix) return false;

  if (normalized.endsWith('.env')) return true;
  return SCAN_EXTENSIONS.has(extname(normalized));
}

function listTrackedFiles() {
  const files = [];
  const ignoredDirectories = new Set([
    '.git',
    'node_modules',
    'dist',
    'coverage',
    'playwright-report',
    'test-results',
  ]);

  function isMissingPathError(error) {
    return error instanceof Error && 'code' in error && error.code === 'ENOENT';
  }

  function walk(relativeDir) {
    const absoluteDir = join(ROOT_DIR, relativeDir);
    let entries;
    try {
      entries = readdirSync(absoluteDir);
    } catch (error) {
      if (isMissingPathError(error)) return;
      throw error;
    }

    for (const entry of entries) {
      if (ignoredDirectories.has(entry)) continue;

      const nextRelative = relativeDir ? `${relativeDir}/${entry}` : entry;
      const nextAbsolute = join(ROOT_DIR, nextRelative);
      let stats;
      try {
        stats = statSync(nextAbsolute);
      } catch (error) {
        if (isMissingPathError(error)) continue;
        throw error;
      }

      if (stats.isDirectory()) {
        walk(nextRelative);
        continue;
      }

      if (stats.isFile()) {
        files.push(toPosix(nextRelative));
      }
    }
  }

  walk('');
  return files;
}

function validateEnvironment() {
  const issues = [];

  const localEnvPath = join(ROOT_DIR, '.env.local');
  if (!existsSync(localEnvPath)) {
    issues.push({
      severity: 'AVISO',
      message: '.env.local nao encontrado - crie a partir de .env.local.example',
    });
  }

  const envPath = join(ROOT_DIR, '.env');
  if (existsSync(envPath)) {
    const envContent = readFileSync(envPath, 'utf-8');

    if (envContent.includes('VITE_SUPABASE_SERVICE_ROLE_KEY=')) {
      issues.push({
        severity: 'CRITICO',
        message: '.env contem VITE_SUPABASE_SERVICE_ROLE_KEY - isso expoe chave sensivel no frontend',
      });
    }

    if (
      envContent.includes('E2E_USER_PASSWORD=') &&
      !envContent.includes('E2E_USER_PASSWORD="[') &&
      !envContent.includes('# E2E Test Credentials (MOVIDO')
    ) {
      issues.push({
        severity: 'CRITICO',
        message: '.env contem credenciais de teste - mova para .env.local',
      });
    }
  }

  for (const envFile of VERSIONABLE_ENV_FILES) {
    const filePath = join(ROOT_DIR, envFile);
    if (!existsSync(filePath)) continue;

    const envContent = readFileSync(filePath, 'utf-8');
    for (const rawLine of envContent.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line || line.startsWith('#')) continue;

      const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
      if (!match) continue;

      const [, name, value] = match;
      if (!SENSITIVE_ENV_NAME_PATTERN.test(name)) continue;
      if (isPlaceholderEnvValue(value)) continue;

      issues.push({
        severity: 'CRITICO',
        message: `${envFile} contem valor real em variavel sensivel (${name}) - mova para .env.local ou secrets do provedor`,
      });
    }
  }

  return issues;
}

function scanFile(relativePath, check) {
  if (shouldExclude(relativePath, check.exclude)) {
    return [];
  }

  const absolutePath = join(ROOT_DIR, relativePath);

  try {
    const content = readFileSync(absolutePath, 'utf-8');
    const issues = [];

    for (const pattern of check.patterns) {
      const matches = content.match(pattern);
      if (matches?.length) {
        issues.push({
          severity: check.severity,
          check: check.name,
          file: relativePath,
          matches: matches.length,
        });
      }
    }

    return issues;
  } catch {
    return [];
  }
}

function listEdgeFunctionNames() {
  if (!existsSync(EDGE_FUNCTIONS_DIR)) return [];

  return readdirSync(EDGE_FUNCTIONS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('_'))
    .map((entry) => entry.name);
}

function validateEdgeFunctionServiceRoleGuards() {
  const serviceRoleFunctionContents = new Map();
  const implementedFunctionNames = listEdgeFunctionNames();

  for (const functionName of implementedFunctionNames) {
    const indexPath = join(EDGE_FUNCTIONS_DIR, functionName, 'index.ts');
    if (!existsSync(indexPath)) continue;

    const content = readFileSync(indexPath, 'utf-8');
    if (!EDGE_FUNCTION_SERVICE_ROLE_PATTERN.test(content)) continue;
    EDGE_FUNCTION_SERVICE_ROLE_PATTERN.lastIndex = 0;
    serviceRoleFunctionContents.set(functionName, content);
  }

  return validateEdgeFunctionServiceRoleCoverage({
    authPolicy: EDGE_FUNCTION_AUTH_POLICY,
    implementedFunctionNames,
    serviceRoleFunctionContents,
    fileForFunction: (functionName) => toPosix(`supabase/functions/${functionName}/index.ts`),
  });
}

function validateEdgeFunctionAuthConfig() {
  const issues = [];
  const relativeConfigPath = 'supabase/config.toml';

  if (!existsSync(SUPABASE_CONFIG_PATH)) {
    issues.push({
      severity: 'CRITICO',
      check: 'Config Supabase ausente',
      file: relativeConfigPath,
      message: 'supabase/config.toml e obrigatorio para auditar verify_jwt das Edge Functions',
    });
    return issues;
  }

  const configContent = readFileSync(SUPABASE_CONFIG_PATH, 'utf-8');
  const implementedFunctionNames = listEdgeFunctionNames();
  const { issues: contractIssues } = validateEdgeFunctionAuthConfigContract({
    authPolicy: EDGE_FUNCTION_AUTH_POLICY,
    configContent,
    configFile: relativeConfigPath,
    implementedFunctionNames,
  });
  issues.push(...contractIssues);

  const implementedFunctionNameSet = new Set(implementedFunctionNames);
  for (const functionName of EDGE_FUNCTION_NO_JWT_ALLOWLIST) {
    const relativeFunctionPath = toPosix(`supabase/functions/${functionName}/index.ts`);
    const absoluteFunctionPath = join(ROOT_DIR, relativeFunctionPath);

    if (!implementedFunctionNameSet.has(functionName)) {
      continue;
    }

    if (!existsSync(absoluteFunctionPath)) {
      issues.push({
        severity: 'CRITICO',
        check: 'Edge Function sem JWT sem implementacao auditavel',
        file: relativeFunctionPath,
        message: `${functionName} esta na allowlist sem JWT, mas index.ts nao foi encontrado`,
      });
      continue;
    }

    const content = readFileSync(absoluteFunctionPath, 'utf-8');
    const policy = EDGE_FUNCTION_AUTH_POLICY.noJwtAllowlist[functionName];
    issues.push(...validateNoJwtEdgeFunctionControls(functionName, policy, content, relativeFunctionPath));
  }

  return issues;
}

