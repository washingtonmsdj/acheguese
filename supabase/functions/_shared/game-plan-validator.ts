export type OrdaxGameType = "platformer" | "topdown" | "shooter" | "puzzle" | "racing" | "sports" | "unknown";
export type GameLoopType = "winlose" | "survival" | "objective";
export type LifecycleSignal = "player_health" | "objective_progress" | "timer";
export type LifecycleState = "start" | "playing" | "gameover";
export type LifecycleTransition = "start->playing" | "playing->gameover" | "gameover->restart";
export type LifecycleUI = "hud" | "gameover_screen";
export type LifecycleControl = "start_game" | "restart_game";

export interface GamePlan {
  kind: "GAME_PLAN";
  gameType: OrdaxGameType;
  title: string;
  description: string;
  coreLoop: string;
  requiredSystems: string[];
  requiredEntities: string[];
  loopType: GameLoopType;
  lifecycle: {
    requiredStates: LifecycleState[];
    requiredTransitions: LifecycleTransition[];
    requiredUI: LifecycleUI[];
    requiredSignalsAnyOf: LifecycleSignal[];
    signal: LifecycleSignal;
    requiredControls: LifecycleControl[];
    startCondition: string;
    loseCondition: string;
    winCondition?: string;
    scoreRule: string;
  };
  mustHave: {
    hasEnemies: boolean;
    hasAI: boolean;
    hasScore: boolean;
    hasHUD: boolean;
    hasSpawner: boolean;
  };
}

export interface PlanDiff {
  autoAddedSystems: string[];
  autoAddedEntities: string[];
  coreLoopAutoGenerated: boolean;
  loopTypeAutoFixed: boolean;
  lifecycle: {
    autoAddedStates: string[];
    autoAddedTransitions: string[];
    autoAddedUI: string[];
    autoAddedControls: string[];
    requiredSignalsAnyOfAutoAdded: boolean;
    signalAutoChosen: boolean;
    startConditionAutoAdded: boolean;
    loseConditionAutoAdded: boolean;
    winConditionAutoAdded: boolean;
    scoreRuleAutoAdded: boolean;
  };
}

// Sistemas constitucionais obrigatórios (sempre necessários)
