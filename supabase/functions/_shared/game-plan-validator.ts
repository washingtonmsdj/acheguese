// Todos os sistemas permitidos (constitucionais + opcionais)
const ORDAX_ALLOWED_SYSTEMS = [...CONSTITUTIONAL_SYSTEMS, ...OPTIONAL_SYSTEMS] as const;

// Validar unicidade
const ALLOWED_SYSTEM_SET = new Set<string>(ORDAX_ALLOWED_SYSTEMS);
if (ALLOWED_SYSTEM_SET.size !== ORDAX_ALLOWED_SYSTEMS.length) {
  console.warn("[game-plan-validator] ⚠️ Sistemas duplicados detectados em ORDAX_ALLOWED_SYSTEMS");
}

function uniq(list: (string | null | undefined)[]): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const s of list) {
    if (!isNonEmptyString(s) || seen.has(s)) continue;
    seen.add(s);
    out.push(s);
  }
  return out;
}

function containsAny(haystack: string, needles: (string | null | undefined)[]): boolean {
  if (!isNonEmptyString(haystack) || !Array.isArray(needles)) {
    return false;
  }
  const t = safeToLowerCase(haystack);
  return needles.some((n) => isNonEmptyString(n) && t.includes(safeToLowerCase(n)));
}

function requiredSystemsForGenre(gameType: OrdaxGameType): string[] {
  // Validate gameType
  const validatedGameType = validateOrdaxGameType(gameType);
  
  // Sistemas base do gênero
  const base = ["CameraSystem", "UISystem"];
  
  switch (validatedGameType) {
    case "puzzle":
      return [...CONSTITUTIONAL_SYSTEMS, ...base, "ScoreSystem", "TimerSystem"];
    case "racing":
    case "sports":
      return [...CONSTITUTIONAL_SYSTEMS, ...base, "PhysicsSystem", "CollisionSystem", "TimerSystem", "ScoreSystem"];
    case "platformer":
      return [...CONSTITUTIONAL_SYSTEMS, ...base, "PhysicsSystem", "CollisionSystem", "ScoreSystem"];
    case "topdown":
      return [...CONSTITUTIONAL_SYSTEMS, ...base, "PhysicsSystem", "CollisionSystem", "AISystem", "SpawnerSystem", "ScoreSystem", "TimerSystem"];
    case "shooter":
      return [...CONSTITUTIONAL_SYSTEMS, ...base, "PhysicsSystem", "CollisionSystem", "AISystem", "SpawnerSystem", "ScoreSystem", "TimerSystem"];
    default:
      // Fallback mais conservador: apenas sistemas constitucionais e base
      return [...CONSTITUTIONAL_SYSTEMS, ...base];
  }
}

function requiredEntitiesForGenre(gameType: OrdaxGameType): string[] {
  // Validate gameType
  const validatedGameType = validateOrdaxGameType(gameType);
  
  const base = ["player"];
  switch (validatedGameType) {
    case "platformer":
      return [...base, "spawner", "enemy", "pickup"];
    case "shooter":
      return [...base, "spawner", "enemy", "pickup"];
    case "topdown":
      return [...base, "spawner", "enemy", "pickup"];
    case "puzzle":
      return [...base, "pickup"];
    case "racing":
      return [...base, "goal", "pickup"];
    case "sports":
      return [...base, "goal", "pickup"];
    default:
      return [...base, "spawner", "enemy", "pickup"];
  }
}

function sanitizeEntities(entities: unknown): string[] {
  const list = validateArrayParam(entities, "entities", (e): e is string => typeof e === "string");
  const allowedSet = new Set<string>(ALLOWED_ENTITIES);
  return uniq(list
    .map((s) => safeTrim(safeToLowerCase(s)))
    .filter((s) => isNonEmptyString(s) && allowedSet.has(s)));
}

function sanitizeSystems(systems: unknown): string[] {
  const list = validateArrayParam(systems, "systems", (s): s is string => typeof s === "string");
  return uniq(list.filter((s) => isNonEmptyString(s) && ALLOWED_SYSTEM_SET.has(s)));
}

function detectLoopType(coreLoop: string): GameLoopType {
  const t = safeToLowerCase(coreLoop);
  if (containsAny(t, LOOP_TYPE_KEYWORDS.survival)) return "survival";
  if (containsAny(t, LOOP_TYPE_KEYWORDS.winlose)) return "winlose";
  return "objective";
}

