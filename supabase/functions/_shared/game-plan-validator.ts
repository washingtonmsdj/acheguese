function promptRequiredSystems(prompt: string): { systems: string[]; notes: string[] } {
  const notes: string[] = [];
  const systems: string[] = [];

  for (const mapping of PROMPT_KEYWORD_MAPPINGS) {
    if (containsAny(prompt, mapping.keywords)) {
      systems.push(mapping.system);
      notes.push(mapping.note);
    }
  }

  return { systems: uniq(systems), notes };
}

function pickDefaultSignal(loopType: GameLoopType, mustHave: GamePlan["mustHave"], requiredEntities: string[]): LifecycleSignal {
  const validatedLoopType = validateGameLoopType(loopType);
  if (mustHave.hasEnemies || requiredEntities.includes("enemy")) return "player_health";
  if (validatedLoopType === "objective") return "objective_progress";
  return "timer";
}

function defaultLoseCondition(gameType: OrdaxGameType, signal: LifecycleSignal, loopType: GameLoopType): string {
  const validatedSignal = validateLifecycleSignal(signal);
  
  // Baseado no signal
  if (validatedSignal === "player_health") return "player_health <= 0";
  if (validatedSignal === "objective_progress") return "objective_progress <= 0";
  
  // Fallback para timer
  return "timer <= 0";
}

function defaultWinCondition(loopType: GameLoopType, signal: LifecycleSignal, mustHave: GamePlan["mustHave"]): string {
  const validatedLoopType = validateGameLoopType(loopType);
  const validatedSignal = validateLifecycleSignal(signal);
  
  if (validatedLoopType === "survival") return "sobreviver o máximo possível";
  if (validatedSignal === "objective_progress") return "objective_progress >= 1";
  if (validatedLoopType === "winlose" && mustHave.hasScore) return "score >= 10";
  return "completar objetivo";
}

function defaultScoreRule(gameType: OrdaxGameType, loopType: GameLoopType, mustHave: GamePlan["mustHave"]): string {
  if (!mustHave.hasScore) return SCORE_RULES.optional;
  
  switch (gameType) {
    case "platformer":
      return loopType === "survival" ? SCORE_RULES.platformerSurvival : SCORE_RULES.platformerDefault;
    case "shooter":
      return loopType === "survival" ? SCORE_RULES.shooterSurvival : SCORE_RULES.shooterDefault;
    case "topdown":
      return loopType === "survival" ? SCORE_RULES.topdownSurvival : SCORE_RULES.topdownDefault;
    case "racing":
      return SCORE_RULES.racing;
    case "sports":
      return SCORE_RULES.sports;
    case "puzzle":
      return SCORE_RULES.puzzle;
    default:
      return SCORE_RULES.default;
  }
}

function normalizeLifecycle(input: unknown) {
  // Type-safe extraction without 'as any'
  const inputObj = input && typeof input === 'object' ? input as Record<string, unknown> : {};
  
  // Extract and validate arrays using type guards
  const states = filterValidLifecycleStates(Array.isArray(inputObj.requiredStates) ? inputObj.requiredStates : []);
  const transitions = filterValidLifecycleTransitions(Array.isArray(inputObj.requiredTransitions) ? inputObj.requiredTransitions : []);
  const ui = filterValidLifecycleUIs(Array.isArray(inputObj.requiredUI) ? inputObj.requiredUI : []);
  const controls = filterValidLifecycleControls(Array.isArray(inputObj.requiredControls) ? inputObj.requiredControls : []);
  const anyOf = filterValidLifecycleSignals(Array.isArray(inputObj.requiredSignalsAnyOf) ? inputObj.requiredSignalsAnyOf : []);

  // Validate single values
  const signal = isLifecycleSignal(inputObj.signal) ? inputObj.signal : undefined;
  const startCondition = validateStringParam(inputObj.startCondition, "startCondition", "");
  const loseCondition = validateStringParam(inputObj.loseCondition, "loseCondition", "");
  const winCondition = validateStringParam(inputObj.winCondition, "winCondition", "");
  const scoreRule = validateStringParam(inputObj.scoreRule, "scoreRule", "");

  return {
    states: uniq(states),
    transitions: uniq(transitions),
    ui: uniq(ui),
    controls: uniq(controls),
    requiredSignalsAnyOf: uniq(anyOf),
    signal,
    startCondition: startCondition || undefined,
    loseCondition: loseCondition || undefined,
    winCondition: winCondition || undefined,
    scoreRule: scoreRule || undefined,
  };
}

// Helper functions for validateAndCompletePlan
function validateInputAndExtractData(input: unknown, userPrompt: string) {
  const inputObj = input && typeof input === 'object' ? input as Record<string, unknown> : {};
  const gameType = validateOrdaxGameType(inputObj.gameType ?? "unknown");
  
  return {
    inputObj,
    gameType,
    userPrompt: validateStringParam(userPrompt, "userPrompt", "")
  };
}

function collectRequiredSystems(gameType: OrdaxGameType, userPrompt: string, inputObj: Record<string, unknown>) {
  const genreReq = requiredSystemsForGenre(gameType);
  const promptReq = promptRequiredSystems(userPrompt);
  const rawSystems = sanitizeSystems(inputObj.requiredSystems);
  
  return { genreReq, promptReq, rawSystems };
}

function collectRequiredEntities(gameType: OrdaxGameType, inputObj: Record<string, unknown>) {
  const genreEntities = requiredEntitiesForGenre(gameType);
  const rawEntities = sanitizeEntities(inputObj.requiredEntities);
  
  return { genreEntities, rawEntities };
}

function buildMustHave(gameType: OrdaxGameType, requiredSystems: string[]) {
  return {
    hasHUD: true,
    hasScore: requiredSystems.includes("ScoreSystem"),
    hasSpawner: requiredSystems.includes("SpawnerSystem"),
    hasAI: requiredSystems.includes("AISystem"),
    hasEnemies: gameType === "topdown" || gameType === "shooter" || gameType === "platformer" ? true : false,
  };
}

function buildLifecycleData(
  inputObj: Record<string, unknown>,
  loopType: GameLoopType,
  mustHave: ReturnType<typeof buildMustHave>,
  requiredEntities: string[],
  gameType: OrdaxGameType
) {
  const rawLifecycle = normalizeLifecycle(inputObj.lifecycle);
  const baseStates: LifecycleState[] = ["start", "playing", "gameover"];
  const baseTransitions: LifecycleTransition[] = ["start->playing", "playing->gameover", "gameover->restart"];
  const baseUI: LifecycleUI[] = ["hud", "gameover_screen"];
  const baseControls: LifecycleControl[] = ["start_game", "restart_game"];
  const baseSignalsAnyOf: LifecycleSignal[] = ["player_health", "objective_progress", "timer"];

  const states = uniq([...rawLifecycle.states, ...baseStates]) as LifecycleState[];
  const transitions = uniq([...rawLifecycle.transitions, ...baseTransitions]) as LifecycleTransition[];
  const ui = uniq([...rawLifecycle.ui, ...baseUI]) as LifecycleUI[];
  const controls = uniq([...rawLifecycle.controls, ...baseControls]) as LifecycleControl[];
  const requiredSignalsAnyOf = uniq([...rawLifecycle.requiredSignalsAnyOf, ...baseSignalsAnyOf]) as LifecycleSignal[];

  const computedSignal = rawLifecycle.signal ?? pickDefaultSignal(loopType, mustHave, requiredEntities);
  const startCondition = rawLifecycle.startCondition ?? "Jogador clica em 'Iniciar'";
  const loseCondition = rawLifecycle.loseCondition ?? defaultLoseCondition(gameType, computedSignal, loopType);
  const winCondition = rawLifecycle.winCondition ?? defaultWinCondition(loopType, computedSignal, mustHave);
  const scoreRule = rawLifecycle.scoreRule ?? defaultScoreRule(gameType, loopType, mustHave);

  return {
    rawLifecycle,
    states,
    transitions,
    ui,
    controls,
    requiredSignalsAnyOf,
    computedSignal,
    startCondition,
    loseCondition,
    winCondition,
    scoreRule
  };
}

function buildPlanDiff(
  rawSystems: string[],
  requiredSystems: string[],
  rawEntities: string[],
  requiredEntities: string[],
  inputObj: Record<string, unknown>,
  rawLifecycle: ReturnType<typeof normalizeLifecycle>,
  states: LifecycleState[],
  transitions: LifecycleTransition[],
  ui: LifecycleUI[],
  controls: LifecycleControl[]
): PlanDiff {
  const lifecycleObj = inputObj.lifecycle && typeof inputObj.lifecycle === 'object' ? inputObj.lifecycle as Record<string, unknown> : {};
  
  return {
    autoAddedSystems: requiredSystems.filter((s) => !rawSystems.includes(s)),
    autoAddedEntities: requiredEntities.filter((e) => !rawEntities.includes(e)),
    coreLoopAutoGenerated: !inputObj.coreLoop,
    loopTypeAutoFixed: !inputObj.loopType,
    lifecycle: {
      autoAddedStates: states.filter((s) => !rawLifecycle.states.includes(s)),
      autoAddedTransitions: transitions.filter((t) => !rawLifecycle.transitions.includes(t)),
      autoAddedUI: ui.filter((u) => !rawLifecycle.ui.includes(u)),
      autoAddedControls: controls.filter((c) => !rawLifecycle.controls.includes(c)),
      requiredSignalsAnyOfAutoAdded: !lifecycleObj.requiredSignalsAnyOf,
      signalAutoChosen: !rawLifecycle.signal,
      startConditionAutoAdded: !rawLifecycle.startCondition,
      loseConditionAutoAdded: !rawLifecycle.loseCondition,
      winConditionAutoAdded: !rawLifecycle.winCondition,
      scoreRuleAutoAdded: !rawLifecycle.scoreRule,
    },
  };
}

export function validateAndCompletePlan(
  input: unknown,
  userPrompt: string
): { plan: GamePlan; warnings: string[]; diff: PlanDiff } {
  const warnings: string[] = [];
  
  // Step 1: Validate input and extract data
  const { inputObj, gameType, userPrompt: validatedPrompt } = validateInputAndExtractData(input, userPrompt);
  
  // Step 2: Collect required systems
  const { genreReq, promptReq, rawSystems } = collectRequiredSystems(gameType, validatedPrompt, inputObj);
  
  // Step 3: Collect required entities
  const { genreEntities, rawEntities } = collectRequiredEntities(gameType, inputObj);
  
  // Step 4: Build required systems and entities with validation
  let requiredEntities = uniq([...rawEntities, ...genreEntities]);
  let requiredSystems = uniq([...rawSystems, ...genreReq, ...promptReq.systems]);

  // Add missing required systems with warnings
  for (const s of genreReq) {
    if (!requiredSystems.includes(s)) {
      requiredSystems.push(s);
      warnings.push(`Plano incompleto: adicionado system obrigatório do gênero: ${s}`);
    }
  }
  for (const s of promptReq.systems) {
    if (!requiredSystems.includes(s)) {
      requiredSystems.push(s);
      warnings.push(`Plano incompleto: adicionado system exigido pelo prompt: ${s}`);
    }
  }

  // Step 5: Build mustHave object
  const mustHave = buildMustHave(gameType, requiredSystems);

  // Add AI and Spawner systems if enemies are required
  if (mustHave.hasEnemies && !requiredSystems.includes("AISystem")) {
    requiredSystems.push("AISystem");
    warnings.push("Gênero exige inimigos: adicionado AISystem");
  }
  if (mustHave.hasEnemies && !requiredSystems.includes("SpawnerSystem")) {
    requiredSystems.push("SpawnerSystem");
    warnings.push("Gênero exige inimigos: adicionado SpawnerSystem");
  }

  // Step 6: Determine core loop and loop type
  const coreLoop = validateStringParam(inputObj.coreLoop, "coreLoop", "Jogador controla personagem e completa objetivos");
  const loopType = detectLoopType(coreLoop);

  // Step 7: Build lifecycle data
  const lifecycleData = buildLifecycleData(inputObj, loopType, mustHave, requiredEntities, gameType);

  // Step 8: Build fallbacks específicos por gameType
  const titleFallback = TITLE_FALLBACKS[gameType] || TITLE_FALLBACKS.default;
  const descriptionFallback = DESCRIPTION_FALLBACKS[gameType] || DESCRIPTION_FALLBACKS.default;

  // Step 9: Build final plan
  const plan: GamePlan = {
    kind: "GAME_PLAN",
    gameType,
    title: validateStringParam(inputObj.title, "title", titleFallback),
    description: validateStringParam(inputObj.description, "description", descriptionFallback),
    coreLoop,
    requiredSystems,
    requiredEntities,
    loopType,
    lifecycle: {
      requiredStates: lifecycleData.states,
      requiredTransitions: lifecycleData.transitions,
      requiredUI: lifecycleData.ui,
      requiredSignalsAnyOf: lifecycleData.requiredSignalsAnyOf,
      signal: lifecycleData.computedSignal,
      requiredControls: lifecycleData.controls,
      startCondition: lifecycleData.startCondition,
      loseCondition: lifecycleData.loseCondition,
      winCondition: lifecycleData.winCondition,
      scoreRule: lifecycleData.scoreRule,
    },
    mustHave,
  };

  // Step 10: Build diff
  const diff = buildPlanDiff(
    rawSystems,
    requiredSystems,
    rawEntities,
    requiredEntities,
    inputObj,
    lifecycleData.rawLifecycle,
    lifecycleData.states,
    lifecycleData.transitions,
    lifecycleData.ui,
    lifecycleData.controls
  );

  return { plan, warnings, diff };
}
